test('登录错误与站外返回地址不会绕过认证', async ({ page }) => {
  await page.goto('/login?next=https://evil.example')
  await page.getByLabel('用户名', { exact:true }).fill('not_registered')
  await page.getByLabel('密码', { exact:true }).fill('wrong-password-123')
  await page.getByRole('button', { name:'登录', exact:true }).click()
  await expect(page.getByRole('alert')).toContainText('用户名或密码不正确')
  await expect(page).toHaveURL(/\/login/)
})

test('键盘可完成登录表单并收到错误反馈', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('用户名', { exact:true }).focus()
  await page.keyboard.type('missing_keyboard_user')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('密码', { exact:true })).toBeFocused()
  await page.keyboard.type('incorrect-password-123')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name:'显示密码' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name:'登录', exact:true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('alert')).toContainText('用户名或密码不正确')
})
