import { test, expect } from '@playwright/test'

test('无效图片明确报错，模拟判卷失败进入终态并停止轮询', async ({ page }) => {
  await page.setViewportSize({ width:390, height:900 })
  await page.goto('/register')
  await page.getByLabel('用户名', { exact:true }).fill(`fail_${Date.now()}`)
  await page.getByLabel('密码', { exact:true }).fill('Test-password-12345')
  await page.getByLabel('确认密码', { exact:true }).fill('Test-password-12345')
  await page.getByRole('button', { name:'创建账号' }).click()
  await page.getByRole('button', { name:'新建备考计划' }).click()
  await page.getByLabel('课程名称').fill('高等数学')
  await page.getByLabel('考试日期').fill('2099-06-21')
  await page.getByRole('button', { name:'保存并开始诊断' }).click()
  await page.getByLabel('选择答题图片').setInputFiles({ name:'broken.png', mimeType:'image/png', buffer:Buffer.from('invalid image') })
  await page.getByRole('button', { name:'上传并开始模拟判卷' }).click()
  await expect(page.getByRole('alert')).toContainText('文件不是有效的')
  await page.getByRole('button', { name:'移除 broken.png' }).click()
  await page.getByLabel('选择答题图片').setInputFiles({ name:'answer.png', mimeType:'image/png', buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAABQAAAAUCAIAAAAC64paAAAALElEQVR4nGP8//8/A7mAiWydDKOaSQZMpGtBgFHNJAImUjUgg1HNJAKKAgwAnKADJa4TmNgAAAAASUVORK5CYII=','base64') })
  await page.getByRole('button', { name:'上传并开始模拟判卷' }).click()
  await expect(page.getByText('判卷失败', { exact:true })).toBeVisible({ timeout:10000 })
  await expect(page.getByRole('alert')).toContainText('图片无法识别')
  await expect(page.getByRole('button', { name:'查看示例诊断' })).toHaveCount(0)
  let polls=0
  page.on('request', request => { if (/\/api\/v1\/grading\//.test(request.url())) polls++ })
  await page.waitForTimeout(2300)
  expect(polls).toBe(0)
  await page.screenshot({ path:'../artifacts/workflow-failure-mobile.png', fullPage:true })
  await page.reload()
  await expect(page.getByText('判卷失败', { exact:true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
