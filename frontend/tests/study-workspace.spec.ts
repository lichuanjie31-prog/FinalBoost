import { test, expect } from '@playwright/test'

test('上传批改与 AI 对话共享当前考试，失败后保留问题', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('用户名', { exact: true }).fill('study_' + Date.now())
  await page.getByLabel('密码', { exact: true }).fill('Test-password-12345')
  await page.getByLabel('确认密码', { exact: true }).fill('Test-password-12345')
  await page.getByRole('button', { name: '创建账号' }).click()
  await expect(page).toHaveURL('/app')
  await expect(page.getByRole('link', { name: 'AI 学伴' })).toHaveCount(0)
  await page.screenshot({ path: '../artifacts/study-overview-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '新建备考计划' }).click()
  await page.getByLabel('课程名称').fill('数据结构')
  await page.getByLabel('考试日期').fill('2099-06-20')
  await page.getByRole('button', { name: '保存并开始诊断' }).click()
  await expect(page).toHaveURL(/\/app\/exams\//)
  const examId = page.url().split('/').pop()
  await expect(page.getByRole('region', { name: 'AI 备考助手' })).toHaveCount(1)
  await page.screenshot({ path: '../artifacts/study-workspace-desktop.png', fullPage: true })
  await page.getByLabel('选择答题图片').setInputFiles({
    name: 'answer.png', mimeType: 'image/png',
    buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAABQAAAAUCAIAAAAC64paAAAALElEQVR4nGP8//8/A7mAiWydDKOaSQZMpGtBgFHNJAImUjUgg1HNJAKKAgwAnKADJa4TmNgAAAAASUVORK5CYII=', 'base64'),
  })
  await expect(page.getByRole('img', { name: 'answer.png' })).toBeVisible()
  await page.getByRole('button', { name: '上传并开始模拟判卷' }).click()
  await expect(page.getByText('判卷完成', { exact: true })).toBeVisible({ timeout: 15000 })
  await expect(page.getByText('已关联所选批改结果')).toBeVisible()
  const sent = page.waitForRequest(r => r.url().endsWith('/agent/chat') && r.method() === 'POST')
  await page.getByRole('button', { name: '分析这次判卷结果' }).click()
  const body = (await sent).postDataJSON()
  expect(body.examId).toBe(examId)
  expect(body.gradingId).toBeTruthy()
  await expect(page.locator('.study-message.assistant')).toHaveCount(1)
  await expect(page.locator('.study-message.user')).toHaveCount(1)
  await page.screenshot({ path: '../artifacts/study-result-desktop.png', fullPage: true })
  await page.route('**/api/v1/agent/chat', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ message: '模型暂时不可用' }) }))
  await page.getByLabel('继续追问').fill('应该如何复习图论？')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('模型暂时不可用')
  await expect(page.getByLabel('继续追问')).toHaveValue('应该如何复习图论？')
  await page.unroute('**/api/v1/agent/chat')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.study-message.assistant')).toHaveCount(2)
  for (const width of [375, 768]) {
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('heading', { name: '数据结构', exact: true }).click()
    await page.evaluate(() => window.scrollTo(0, 0))
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: '../artifacts/study-result-' + width + '.png', fullPage: true })
  }
})
